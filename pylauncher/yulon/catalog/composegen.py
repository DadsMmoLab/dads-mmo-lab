def _container_prefix(entry: CatalogEntry) -> str:
    """The part the three container names share: `ac-` for WotLK, `tbc-` for TBC.

    The shared CMaNGOS templates name services `{{CONTAINER_PREFIX}}db`,
    `..realmd`, `..mangosd` so they equal the entry's container names — the
    AzerothCore convention `docker.start_database()` relies on. Derived rather
    than declared, so the catalog cannot say two different things.

    Deriving it is right; deriving it with `os.path.commonprefix` and TRUSTING
    the answer was not. That function is character-wise, not separator- or
    token-aware, and it never raises: three names sharing no first character
    answer `""`, `db`/`dbauth`/`dbworld` answer `"db"` (so
    `{{CONTAINER_PREFIX}}db` renders `dbdb`), and `abc-db`/`abcd-realmd`/
    `abcx-mangosd` answer `"abc"`, with the separator eaten. Every one of those
    is a filled-but-wrong token, and `fill()` has no opinion about those — it
    refuses an UNFILLED placeholder — so the first thing to report it would be
    `docker compose up` naming a container no service owns. Two rules follow,
    and both are about what the catalog is ALLOWED to say, not about what the
    prefix happens to come out as:

    * an empty prefix is refused outright. It cannot be right for any entry.
    * `containers.services` is refused outright, whatever its value. This module
      writes the compose file, and the service keys in it are the templates' own
      — read 2026-09-04: `shared/cmangos/base.yml.tmpl` writes
      `{{CONTAINER_PREFIX}}db`/`realmd`/`mangosd`, `wow-wotlk/native/base.yml.tmpl`
      writes the literal `ac-database`/`ac-authserver`/`ac-worldserver` — so a
      declaration on the entry can only restate them or contradict them.

    What the refusal is allowed to say, measured 2026-09-04 on m910q (§30,
    round 2): the first rewrite of this rule refused the declaration and then
    named the entry's three container names as "the names compose must be
    given". With containers `db`/`dbauth`/`dbworld` the shared/cmangos
    templates rendered the keys `dbdb`/`dbrealmd`/`dbmangosd`, so every name in
    that advice answered `no such service` — the headline complaint of §30,
    reproduced by its fix. The suffix a template writes is not known here, so
    the refusal names no service at all; it says what to delete and where the
    names come from, and
    `test_the_refusal_names_no_service_the_rendered_file_does_not_define`
    renders the shape and holds the text to that.

    Until 2026-09-04 the second rule was the opposite: an entry declaring
    `containers.services` was accepted when the prefix rebuilt the container
    names from them, `container == prefix + service`. Probed on the shipped
    `wow-tbc` entry (bug-checklist §30) it answered backwards —

        ("tbc-db","tbc-realmd","tbc-mangosd")  -> REFUSED: 'tbc-' in front of
            those rebuilds tbc-tbc-db, tbc-tbc-realmd, tbc-tbc-mangosd
        ("db","realmd","mangosd")              -> ACCEPTED, prefix 'tbc-',
            and compose_services() then answered those three bare suffixes

    — so the one declaration shape it accepted was the one `docker compose up`
    answers `no such service` for, which is precisely the defect §26 fixed and
    the reason three CMaNGOS entries would have died at the first `up`. A rule
    satisfiable only by the bug it was written to refuse, whose refusal text
    ("Name every container after its service with one shared prefix in front of
    it") read as instructions for reproducing it, handed to whoever adds the
    fifth game.

    Correcting the rule to `service == container` was the other option and was
    rejected: it would accept a declaration that only ever restates what
    `ContainerSpec.compose_services()` already answers when the field is absent,
    and it leaves the next person a second place to write the two names apart.
    Refusing the declaration removes the opportunity instead of documenting it.
    `docker.ContainerSpec.services` itself stays — an ADOPTED project really can
    name its services and containers differently, which the integration suite's
    throwaway stack exercises on purpose — what has no correct value is the
    field on an entry whose compose file this module writes.

    The other two commonprefix shapes are not refused here, and cannot be:
    telling `dbdb` from `tbc-db` needs the literal suffix the template writes
    (`db`, `realmd`, `mangosd`), which lives in the template and not in the
    entry. Rendering first and then checking that every container name is a
    service key of the filled text was considered and rejected — the app has no
    YAML parser among its dependencies, the templates are data (style-guide §3),
    and a generation-time check that reads them would refuse every one-token
    template these tests render. Measured 2026-09-04 against the shipped
    `shared/cmangos` templates instead: containers `db`/`dbauth`/`dbworld` render
    the service keys `dbdb`/`dbrealmd`/`dbmangosd`, and `abc-db`/`abcd-realmd`/
    `abcx-mangosd` render `abcdb`/`abcrealmd`/`abcmangosd` — in neither case a
    name the entry would select, which is exactly the disagreement
    `test_every_service_the_catalog_selects_is_defined_in_the_rendered_compose_file`
    compares for every shipped entry, and
    `test_a_commonprefix_the_template_does_not_share_is_caught_by_the_rendered_file`
    pins on those two shapes. The price of catching it there rather than here,
    stated rather than glossed: a shipped entry fails the suite (that cross-check
    ran on all four shipped entries 2026-09-04), an entry added without running
    the suite fails at `compose up` after the build (the §26 Discord report of
    2026-08-26 is what that looks like).
    """
    services = entry.containers.services
    names = (entry.containers.db, entry.containers.auth, entry.containers.world)
    if services is not None:
        raise ComposeGenError(
            f"{entry.id} declares containers.services ({', '.join(services)}), but this engine "
            "generates the compose file and the service names in it come from the templates, "
            "not from the entry: no value of the field is both correct and needed. Delete "
            f"containers.services from {entry.id}. Whether its container names are then the "
            "services the rendered file defines is checked by rendering it, not here: "
            "test_every_service_the_catalog_selects_is_defined_in_the_rendered_compose_file."
        )
    prefix = os.path.commonprefix(list(names))
    if not prefix:
        raise ComposeGenError(
            f"the container names of {entry.id} ({', '.join(names)}) share no common prefix, "
            "so the container-prefix token would render the bare service names and the stack "
            "would name containers that no service owns. Give the three containers one shared "
            "prefix, as in <game>-db, <game>-realmd and <game>-mangosd."
        )
    return prefix


def entry_tokens(entry: CatalogEntry) -> dict[str, str]:
    """The per-game tokens every template, conf value and SQL statement may use.

    Facts the entry already states, spelled once: `DB_HOST` is the DB container
    (the conf files reach it by that name, not the scripts' bare `db`), the
    schema names are `databases.*`, and `LOGS_DB` is the first `extra` schema
    — omitted, not blanked, when there is none, so a template that wants it
    fails in `fill()` instead of writing `;;` into a conf. `MAKE_JOBS` and
    `CORE_DIR` exist only for a `cmangos` block: `CORE_DIR` is the core's
    in-image install prefix, derived as the parent of `conf.source_dir`
    (`/opt/mangos/etc` → `/opt/mangos`), which is where the binaries, the
    `etc/` bind and the `data/` bind all hang. `CmangosInstaller` adds the
    per-install ones on top of this mapping, in TWO sets since 7.3:
    `_public_tokens()` adds `REALM_HOST`, the three ports, the project name and
    the image prefix and tag, and is what the build context is rendered from;
    `_secret_tokens()` is that plus `DB_PASSWORD`, for the conf tables and
    (K.7) the SQL and verify.

    Raises:
        ComposeGenError: the entry has no `install.native` block, its three
            container names share no prefix, or it declares
            `containers.services` — the last two through `_container_prefix()`,
            which is reached from here and from nowhere else in the app.
    """
    native = _native_of(entry)
    tokens = {
        "DB_IMAGE": native.db.image,
        "DB_HOST": entry.containers.db,
        "DB_USER": native.db.user,
        "AUTH_DB": entry.databases.auth,
        "WORLD_DB": entry.databases.world,
        "CHAR_DB": entry.databases.characters,
        "CONTAINER_PREFIX": _container_prefix(entry),
        "CLIENT_BUILD": str(entry.client.build),
    }
    if entry.databases.extra:
        tokens["LOGS_DB"] = entry.databases.extra[0]
    if native.cmangos is not None:
        tokens["MAKE_JOBS"] = str(native.cmangos.dockerfile.make_jobs)
        tokens["CORE_DIR"] = str(PurePosixPath(native.cmangos.conf.source_dir).parent)
    return tokens


def _env_block(env: Mapping[str, str]) -> str:
    """The override's `environment:` mapping, indented to sit under it.

    Values are double-quoted strings without exception. AzerothCore reads these
    as text, and YAML would otherwise turn `1` into an int and `on` into a
    boolean — a distinction compose passes through to the container as
    `AC_..=true`, which no `.conf` parser expects.
    """
    lines: list[str] = []
    for key in sorted(env):
        if not _is_env_identifier(key):
            raise ComposeGenError(f"{key!r} is not a usable environment variable name")
        _refuse_unsafe(env[key], f"the value of {key}")
        lines.append(f'      {key}: "{env[key]}"')
    return "\n".join(lines)


def _is_env_identifier(key: str) -> bool:
    return (
        bool(key)
        and (key[0].isalpha() or key[0] == "_")
        and all(char.isalnum() or char == "_" for char in key)
    )


def _refuse_unsafe(value: str, what: str) -> None:
    bad = sorted(set(value) & _UNSAFE_SCALAR_CHARS)
    if bad:
        raise ComposeGenError(
            f"{what} contains {' '.join(repr(char) for char in bad)}, which cannot be written "
            "into a compose file safely. Use letters, digits and simple punctuation."
        )


def is_ours(path: Path) -> bool:
    """Did this engine write the file at `path`? Missing counts as ours to write.

    The whole of the rewrite rule (see `GENERATED_MARKER`): only the first line
    is consulted, because that is the one place a marker cannot be introduced
    by accident, and an unreadable file answers False — the fail-closed answer
    for "should I overwrite this".
    """
    if not path.exists():
        return True
    try:
        with path.open(encoding="utf-8", errors="replace") as fh:
            return fh.readline().startswith(GENERATED_MARKER)
    except OSError as exc:
        logger.warning(f"could not read {path} to see whether it is ours: {exc}")
        return False


def write_plan(
    plan: ComposePlan, server_dir: Path, *, replaceable: Sequence[str] = ()
) -> tuple[Path, ...]:
    """Write the three files (and merge `.env`), refusing to overwrite foreign ones.

    Returns the paths written, which is deliberately not always all three: a
    file whose content already matches is left alone so its mtime does not
    move, and an unchanged compose file is what tells a user's own `docker
    compose` that nothing needs recreating.

    `replaceable` names files the CALLER has separately proved may be
    overwritten despite carrying no marker, and it exists for exactly one file:
    `docker-compose.yml`, which the emulator repository ships at its own root.
    The server directory IS that checkout, so on every single install the clone
    stage lays an unmarked `docker-compose.yml` down before this runs, and the
    marker rule alone refused every install with "point the install at an empty
    folder" — told to a user who did, after a 2.4 GB clone (review,
    2026-08-23). This module cannot tell upstream's file from a real server's,
    so it does not guess; `native._generate_compose()` asks git whether the
    file is the tracked, unmodified one the clone wrote and passes the answer
    in. Nothing is replaceable by default.

    Raises:
        ComposeGenError: a compose file exists that this engine did not write
            and the caller did not name. Never deleted, never overwritten — the
            install stops instead, since the alternative is orphaning somebody's
            character volumes.
    """
    written: list[Path] = []
    for name, text in (
        (BASE_FILE, plan.base),
        (OVERRIDE_FILE, plan.override),
        (BUILD_FILE, plan.build),
    ):
        path = server_dir / name
        if name not in replaceable and not is_ours(path):
            raise ComposeGenError(
                f"{path} was not written by Yu'lon, so it was not touched and nothing was "
                "installed. Point the install at an empty folder, or move that file aside."
            )
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    if plan.dotenv:
        written.append(write_dotenv(server_dir, plan.dotenv))
    return tuple(written)


def merge_dotenv(existing: str, additions: Mapping[str, str]) -> str:
    """`.env` text with `additions` applied: existing assignments replaced, new ones appended.

    Reached through `write_plan()` for a generated-password game since 7.1; a
    fixed-password plan never fills `dotenv`, so WotLK never comes here.

    A merge and not a rewrite, because this file is shared. Compose interpolates
    the compose files from it, a later SOAP setup writes its own port binding
    into it, and the port-conflict remedy appends a `DOCKER_DB_EXTERNAL_PORT`
    — dropping a key nobody here recognises would silently undo one of those.

    An assignment is replaced in place so its position (and therefore which
    wins, since compose takes the LAST) does not change.
    """
    lines = existing.splitlines()
    remaining = dict(additions)
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("export "):
            stripped = stripped[len("export ") :].lstrip()
        key = stripped.split("=", 1)[0].strip() if "=" in stripped else ""
        if key in remaining:
            lines[index] = f"{key}={remaining.pop(key)}"
    if remaining:
        if lines and lines[-1].strip():
            lines.append("")
        lines.append("# Written by Yu'lon's install engine.")
        lines += [f"{key}={remaining[key]}" for key in sorted(remaining)]
    return "\n".join(lines) + "\n"


def write_dotenv(server_dir: Path, additions: Mapping[str, str]) -> Path:
    """Merge `additions` into `<server_dir>/.env`, atomically.

    Atomic and byte-preserving for the reason `docker.pin_project_name()` gives
    at length: this file can hold the database root password, and a truncating
    write interrupted by a full disk leaves a `.env` the user's database is no
    longer reachable through.
    """
    path = server_dir / DOTENV_FILE
    existing = path.read_text(encoding="utf-8", errors="replace") if path.is_file() else ""
    merged = merge_dotenv(existing, additions)
    tmp = path.with_name(path.name + ".yulon-new")
    try:
        tmp.write_text(merged, encoding="utf-8", newline="\n")
        os.replace(tmp, path)  # atomic on POSIX and on Windows
    except OSError:
        tmp.unlink(missing_ok=True)
        raise
    return path
