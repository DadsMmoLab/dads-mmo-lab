def test_write_reads_each_file_once_so_a_flaky_read_cannot_accuse_the_user(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """One read answers both questions — may we write, and is the text already right.

    Asking twice (`is_ours()` opens the file, then the equality check opens it again) is
    how a transient read failure turns into "that file was not written by Yu'lon", an
    accusation about the user's folder that the first read had already disproved. The
    file here is readable exactly once.
    """
    text, ignore = dockerfile.render(templates(tmp_path), TOKENS, secrets=SECRETS)
    server = server_dir(tmp_path)
    dockerfile.write(server, text, ignore)
    newer, _ = dockerfile.render(
        templates(tmp_path / "v2"), {**TOKENS, "MAKE_JOBS": "4"}, secrets=SECRETS
    )

    real_open = Path.open
    reads: dict[str, int] = {}

    def counting_open(self: Path, mode: str = "r", *args: object, **kwargs: object) -> object:
        if self.parent == server and "w" not in mode:
            reads[self.name] = reads.get(self.name, 0) + 1
            if reads[self.name] > 1:
                raise PermissionError(13, f"{self.name} was read twice")
        return real_open(self, mode, *args, **kwargs)  # type: ignore[arg-type]

    monkeypatch.setattr(Path, "open", counting_open)
    assert dockerfile.write(server, newer, ignore) == (server / "Dockerfile",)
    assert reads == {"Dockerfile": 1, ".dockerignore": 1}


